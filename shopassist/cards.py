def cards_by_split(split: str) -> list[dict]:
    return [card for card in all_cards() if card["split"] == split]


def public_gallery() -> list[dict]:
    gallery = []
    for card in all_cards():
        gallery.append(
            {
                "card_id": card["card_id"],
                "scenario_id": card["scenario_id"],
                "title": card["title"],
                "summary": card["summary"],
                "split": card["split"],
                "tags": card["tags"],
            }
        )
    return gallery
