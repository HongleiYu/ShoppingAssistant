def _card(card_id, *, scenario_id, template_id, lineage_id, split, title, summary, turns, tags, expected, faults=None):
    return {
        "card_id": card_id,
        "scenario_id": scenario_id,
        "template_id": template_id,
        "lineage_id": lineage_id,
        "split": split,
        "session_id": "sess-" + card_id,
        "seed": zlib.crc32(card_id.encode("utf-8")) % 100000,
        "title": title,
        "summary": summary,
        "turns": turns,
        "faults": list(faults or []),
        "tags": sorted(set(tags)),
        "expected": expected,
    }


def _one(intent, route, slots=None, variant=0):
    return {"intent": intent, "route": route, "slots": slots or {}, "variant": variant}


